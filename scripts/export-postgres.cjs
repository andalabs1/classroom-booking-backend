require('dotenv').config({ quiet: true });
const { PrismaClient } = require('@prisma/client');
const fs = require('node:fs');
const path = require('node:path');

const tables = ['User', 'Classroom', 'Booking', 'AuditLog', 'Notification'];
const jsonColumns = new Set(['equipment', 'requestedEquipment', 'oldValue', 'newValue']);

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;
const literal = (value, column) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'bigint' || typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
  if (value instanceof Date) return `${quote(value.toISOString())}::timestamptz`;
  if (jsonColumns.has(column)) {
    const json = typeof value === 'string' ? value : JSON.stringify(value);
    return `${quote(json)}::jsonb`;
  }
  return quote(value);
};

const schema = `
CREATE TYPE "Role" AS ENUM ('USER', 'STUDENT', 'TEACHER', 'ADMIN');
CREATE TYPE "UserStatus" AS ENUM ('ACTIVE', 'INACTIVE', 'SUSPENDED');
CREATE TYPE "ClassroomStatus" AS ENUM ('ACTIVE', 'INACTIVE', 'MAINTENANCE');
CREATE TYPE "BookingStatus" AS ENUM ('PENDING', 'CONFIRMED', 'IN_USE', 'REJECTED', 'CANCELLED', 'COMPLETED', 'NO_SHOW');

CREATE TABLE "User" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userCode" VARCHAR(50) UNIQUE,
  "name" VARCHAR(150) NOT NULL,
  "firstName" VARCHAR(100), "lastName" VARCHAR(100), "phone" VARCHAR(20),
  "email" VARCHAR(255) NOT NULL UNIQUE,
  "passwordHash" VARCHAR(255) NOT NULL,
  "role" "Role" NOT NULL DEFAULT 'USER',
  "status" "UserStatus" NOT NULL DEFAULT 'ACTIVE',
  "tokenVersion" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "Classroom" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "code" VARCHAR(50) UNIQUE, "name" VARCHAR(100) NOT NULL,
  "building" VARCHAR(100) NOT NULL, "floor" VARCHAR(50) NOT NULL,
  "capacity" INTEGER NOT NULL, "description" TEXT, "category" VARCHAR(100),
  "equipment" JSONB, "imageUrl" VARCHAR(500),
  "status" "ClassroomStatus" NOT NULL DEFAULT 'ACTIVE',
  "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "Booking" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "bookingCode" VARCHAR(30) NOT NULL UNIQUE, "userId" BIGINT NOT NULL,
  "classroomId" BIGINT NOT NULL, "purpose" VARCHAR(255) NOT NULL,
  "attendeeCount" INTEGER NOT NULL DEFAULT 1, "requestedEquipment" JSONB,
  "description" TEXT, "startAt" TIMESTAMPTZ(3) NOT NULL, "endAt" TIMESTAMPTZ(3) NOT NULL,
  "status" "BookingStatus" NOT NULL DEFAULT 'PENDING', "adminNote" TEXT,
  "approvedBy" BIGINT, "approvedAt" TIMESTAMPTZ(3), "checkedInAt" TIMESTAMPTZ(3),
  "completedAt" TIMESTAMPTZ(3), "cancelledAt" TIMESTAMPTZ(3), "cancelReason" TEXT,
  "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "Booking_userId_fkey" FOREIGN KEY ("userId") REFERENCES "User"("id"),
  CONSTRAINT "Booking_classroomId_fkey" FOREIGN KEY ("classroomId") REFERENCES "Classroom"("id"),
  CONSTRAINT "Booking_approvedBy_fkey" FOREIGN KEY ("approvedBy") REFERENCES "User"("id")
);
CREATE TABLE "AuditLog" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "userId" BIGINT,
  "action" TEXT NOT NULL, "entity" TEXT NOT NULL, "entityId" BIGINT,
  "oldValue" JSONB, "newValue" JSONB,
  "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "AuditLog_userId_fkey" FOREIGN KEY ("userId") REFERENCES "User"("id")
);
CREATE TABLE "Notification" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "userId" BIGINT NOT NULL,
  "bookingId" BIGINT, "title" TEXT NOT NULL, "message" TEXT NOT NULL, "type" TEXT NOT NULL,
  "dedupeKey" VARCHAR(191) UNIQUE, "isRead" BOOLEAN NOT NULL DEFAULT FALSE,
  "readAt" TIMESTAMPTZ(3), "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "Notification_userId_fkey" FOREIGN KEY ("userId") REFERENCES "User"("id") ON DELETE CASCADE,
  CONSTRAINT "Notification_bookingId_fkey" FOREIGN KEY ("bookingId") REFERENCES "Booking"("id") ON DELETE SET NULL
);
CREATE INDEX "Booking_userId_idx" ON "Booking" ("userId");
CREATE INDEX "Booking_classroomId_idx" ON "Booking" ("classroomId");
CREATE INDEX "Booking_classroomId_startAt_endAt_status_idx" ON "Booking" ("classroomId", "startAt", "endAt", "status");
CREATE INDEX "Booking_status_idx" ON "Booking" ("status");
CREATE INDEX "Booking_startAt_idx" ON "Booking" ("startAt");
CREATE INDEX "Booking_endAt_idx" ON "Booking" ("endAt");
CREATE INDEX "AuditLog_userId_idx" ON "AuditLog" ("userId");
CREATE INDEX "Notification_userId_idx" ON "Notification" ("userId");
CREATE INDEX "Notification_bookingId_idx" ON "Notification" ("bookingId");
CREATE INDEX "Notification_isRead_idx" ON "Notification" ("isRead");
`;

async function main() {
  const prisma = new PrismaClient();
  const directory = path.resolve('sql_backup', new Date().toISOString().replace(/[:.]/g, '-'));
  fs.mkdirSync(directory, { recursive: true });
  try {
    const data = {};
    for (const table of tables) data[table] = await prisma.$queryRawUnsafe(`SELECT * FROM \`${table}\` ORDER BY id`);
    let sql = '-- PostgreSQL schema and data export from the classroom booking MySQL database.\nBEGIN;\n';
    sql += 'DROP TABLE IF EXISTS "Notification", "AuditLog", "Booking", "Classroom", "User" CASCADE;\n';
    sql += 'DROP TYPE IF EXISTS "BookingStatus", "ClassroomStatus", "UserStatus", "Role" CASCADE;\n';
    sql += schema;
    for (const table of tables) {
      for (const row of data[table]) {
        const columns = Object.keys(row);
        sql += `INSERT INTO "${table}" (${columns.map((column) => `"${column}"`).join(', ')}) VALUES (${columns.map((column) => literal(row[column], column)).join(', ')});\n`;
      }
    }
    for (const table of tables) {
      sql += `SELECT setval(pg_get_serial_sequence('"${table}"', 'id'), COALESCE(MAX("id"), 1), MAX("id") IS NOT NULL) FROM "${table}";\n`;
    }
    sql += 'COMMIT;\n';
    const output = path.join(directory, 'postgresql.sql');
    fs.writeFileSync(output, sql, 'utf8');
    console.log(JSON.stringify({ output, tables: Object.fromEntries(tables.map((table) => [table, data[table].length])) }));
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((error) => { console.error(error.message); process.exitCode = 1; });
